                new ColumnDefinition("Name", "TEXT").NotNull(),
            })
        });

        // v1 → v2: Add Projects table, add Salary column to Users
        var v2 = SchemaSnapshot.FromTableDefinitions("v2", new[]
        {
            new TableDefinition("Users", "public", new[]
            {
                new ColumnDefinition("Id", "BIGINT").PrimaryKey().AutoIncrement(),
                new ColumnDefinition("Name", "TEXT").NotNull(),
                new ColumnDefinition("Email", "TEXT").NotNull(),
