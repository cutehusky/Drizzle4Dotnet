    /// <summary>
    /// Helper to build SQL from an ISql object using the PgSql dialect.
    /// </summary>
    private static (string Sql, Dictionary<string, object?> Parameters) Build(ISql sql)
    {
        var builder = new SqlBuilder<PgSqlSqlDialectImpl>();
        sql.BuildSql(builder);
        var result = builder.Build();
        return (result.Item1, result.Item2);
    }

    private static void Print(string title, string sql)
    {
        TestContext.Out.WriteLine("===== " + title + " =====");
        TestContext.Out.WriteLine(sql);
        TestContext.Out.WriteLine("");
    }

