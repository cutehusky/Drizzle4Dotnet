    [Test]
    public void SchemaSnapshot_SerializeDeserialize()
    {
        var table1 = new TableDefinition("Users", "public", new[]
        {
            new ColumnDefinition("Id", "BIGINT").PrimaryKey(),
            new ColumnDefinition("Name", "TEXT").NotNull(),
        });

        var table2 = new TableDefinition("Departments", "public", new[]
        {
            new ColumnDefinition("Id", "BIGINT").PrimaryKey(),
            new ColumnDefinition("Name", "TEXT").NotNull(),
        });

        var snapshot = SchemaSnapshot.FromTableDefinitions("v1", new[] { table1, table2 });
        var json = snapshot.Serialize();
        Print("Snapshot JSON", json);

        Assert.That(json, Does.Contain("v1"));
        Assert.That(json, Does.Contain("Users"));
        Assert.That(json, Does.Contain("Departments"));
        Assert.That(json, Does.Contain("Id"));
        Assert.That(json, Does.Contain("Name"));

        // Deserialize and verify
        var deserialized = SchemaSnapshot.Deserialize(json);
        Assert.That(deserialized.Name, Is.EqualTo("v1"));
        Assert.That(deserialized.Tables.Count, Is.EqualTo(2));
        Assert.That(deserialized.Tables[0].TableName, Is.EqualTo("Users"));
        Assert.That(deserialized.Tables[0].Columns.Count, Is.EqualTo(2));
    }

