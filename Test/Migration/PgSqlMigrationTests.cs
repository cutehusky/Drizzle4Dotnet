            {
                new ColumnDefinition("Id", "BIGINT").PrimaryKey().AutoIncrement(),
                new ColumnDefinition("Name", "TEXT").NotNull(),
            }),
            new TableDefinition("Projects", "public", new[]
            {
                new ColumnDefinition("Id", "BIGINT").PrimaryKey().AutoIncrement(),
                new ColumnDefinition("Name", "TEXT").NotNull(),
                new ColumnDefinition("DepartmentId", "BIGINT").NotNull(),
            })
        });

        // Migration 1: empty → v1
        var diff1 = empty.Compare(v1);
        var plan1 = diff1.ToMigrationPlan("InitialCreate");
        var sql1 = plan1.ToSql<PgSqlSqlDialectImpl>();
        Print("Migration 1: Initial create", sql1);

        Assert.That(plan1.Steps.Count, Is.EqualTo(2));
        Assert.That(plan1.Steps[0].StepType, Is.EqualTo(MigrationStepType.CreateTable));
        Assert.That(plan1.Steps[0].Description, Does.Contain("Users"));
        Assert.That(plan1.Steps[1].StepType, Is.EqualTo(MigrationStepType.CreateTable));
        Assert.That(plan1.Steps[1].Description, Does.Contain("Departments"));

        // Migration 2: v1 → v2
        var diff2 = v1.Compare(v2);
        var plan2 = diff2.ToMigrationPlan("AddProjectsAndSalary");
        var sql2 = plan2.ToSql<PgSqlSqlDialectImpl>();
        Print("Migration 2: Add projects and salary", sql2);

        Assert.That(plan2.Steps.Count, Is.EqualTo(2));

        // First step: alter Users to add Salary column
        Assert.That(plan2.Steps[0].StepType, Is.EqualTo(MigrationStepType.AlterTable));
        Assert.That(plan2.Steps[0].Description, Does.Contain("Users"));
        Assert.That(sql2, Does.Contain("ADD COLUMN Salary NUMERIC(18,2) DEFAULT 0"));

